import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const sequencesRoot = path.join(root, "public", "sequences");
const outputFile = path.join(root, "src", "generated", "sequenceManifest.ts");
const sequenceOrder = [
  "mona-641-794",
  "mona-641-404",
  "final-642",
  "seed-764",
  "new-mona-lisa",
  "mona-lisa",
  "duck",
  "ofir",
];

/** Gallery groups: artworks of one subject are listed together under the group name, each by its short label. */
const sequenceGroups = {
  "mona-641-794": { group: "Mona Lisa", shortLabel: "641.794" },
  "mona-641-404": { group: "Mona Lisa", shortLabel: "641.404" },
  "final-642": { group: "Mona Lisa", shortLabel: "Final 642" },
  "seed-764": { group: "Mona Lisa", shortLabel: "Seed 764" },
  "new-mona-lisa": { group: "Mona Lisa", shortLabel: "New" },
  "mona-lisa": { group: "Mona Lisa", shortLabel: "Original" },
};

function humanizeZipName(filename) {
  const base = filename.replace(/\.zip$/i, "");
  return base
    .replace(/[-_]+/g, " ")
    .replace(/\s+/g, " ")
    .trim()
    .replace(/\b\w/g, (char) => char.toUpperCase());
}

function zipFilenameToId(filename) {
  return filename
    .replace(/\.zip$/i, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

function listSequenceZipFiles() {
  fs.mkdirSync(sequencesRoot, { recursive: true });
  return fs
    .readdirSync(sequencesRoot)
    .filter((name) => name.toLowerCase().endsWith(".zip"))
    .sort((a, b) => {
      const idA = zipFilenameToId(a);
      const idB = zipFilenameToId(b);
      const orderA = sequenceOrder.indexOf(idA);
      const orderB = sequenceOrder.indexOf(idB);

      if (orderA !== -1 || orderB !== -1) {
        return (
          (orderA === -1 ? Number.POSITIVE_INFINITY : orderA) -
          (orderB === -1 ? Number.POSITIVE_INFINITY : orderB)
        );
      }

      return a.localeCompare(b, undefined, { sensitivity: "base" });
    });
}

function sequenceZipUrlName(filename) {
  return filename.toLowerCase();
}

export function copySequenceZipsTo(outDir) {
  fs.mkdirSync(outDir, { recursive: true });
  for (const file of listSequenceZipFiles()) {
    fs.copyFileSync(
      path.join(sequencesRoot, file),
      path.join(outDir, sequenceZipUrlName(file)),
    );
  }
}

export function generateSequenceManifest() {
  const files = listSequenceZipFiles();
  const manifest = files.map((file) => ({
    id: zipFilenameToId(file),
    label: humanizeZipName(file),
    file: sequenceZipUrlName(file),
    ...sequenceGroups[zipFilenameToId(file)],
  }));

  const manifestSource = [
    "// Auto-generated by scripts/generateSequenceManifest.mjs - do not edit.",
    "",
    "export type SequenceManifestEntry = {",
    "  id: string;",
    "  label: string;",
    "  file: string;",
    "  group?: string;",
    "  shortLabel?: string;",
    "};",
    "",
    `export const SEQUENCE_MANIFEST: SequenceManifestEntry[] = ${JSON.stringify(manifest, null, 2)};`,
    "",
  ].join("\n");

  fs.mkdirSync(path.dirname(outputFile), { recursive: true });
  fs.writeFileSync(outputFile, manifestSource);

  return manifest;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const manifest = generateSequenceManifest();
  console.log(
    `Wrote ${manifest.length} sequence(s) to src/generated/sequenceManifest.ts`,
  );
}
